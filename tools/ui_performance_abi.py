"""Generate private scene/controller callback tags from their Rust definitions."""
from pathlib import Path
import re,sys
repo=Path(__file__).resolve().parents[1]
text=(repo/'rust/fm1-app/src/performance.rs').read_text(encoding='utf-8')
automatic=(repo/'rust/fm1-app/src/automatic.rs').read_text(encoding='utf-8')
cache=re.search(r'pub struct DjState\s*\{(.*?)\}',automatic,re.S).group(1)
assert re.findall(r'pub\s+(\w+)\s*:\s*u8',cache)==['last','intro','map','host','sync'],'DJ cache ABI drift'
lines=['/* SPDX-License-Identifier: GPL-3.0-only */','/* Generated by tools/ui_performance_abi.py. */',
 '#ifndef FM1_RUST_UI_PERFORMANCE_H','#define FM1_RUST_UI_PERFORMANCE_H','#include "rust_ui.h"']
for name,prefix,base in [('Query','UIPQ',0x100),('Action','UIPA',0),('Notice','UIPN',0x200),('Operation','UIPO',0)]:
    body=re.search(r'pub enum '+name+r'\s*\{(.*?)\}',text,re.S).group(1)
    entries=re.findall(r'^\s*(\w+),\s*$',body,re.M)
    assert entries and len(entries)<256
    symbols=[prefix+'_'+re.sub(r'(?<!^)(?=[A-Z])','_',word).upper() for word in entries]
    lines.append('enum {'+symbols[0]+'='+hex(base)+','+','.join(symbols[1:])+'};')
lines+=['/* Initialized foreground UI; all state loans end before synchronous callbacks. */',
 'int32_t fm1_rust_ui_performance(fm1_ui_state*,uint32_t,int32_t,uint32_t(*)(uint32_t,uint32_t,uint32_t));',
 'typedef struct {uint8_t last,intro,map,host,sync;} fm1_ui_dj_state;',
 '_Static_assert(sizeof(fm1_ui_dj_state)==5,"DJ cache replaces five original byte statics");',
 'int32_t fm1_rust_ui_dj_tick(fm1_ui_state*,fm1_ui_dj_state*,uint32_t(*)(uint32_t,uint32_t,uint32_t));',
 'int32_t fm1_rust_ui_auto_metadata(uint32_t,uint32_t,uint32_t*);','#endif','']
output='\n'.join(lines);path=repo/'firmware/src/dsp/rust_ui_performance.h'
if '--check' in sys.argv:
    assert path.read_text(encoding='utf-8')==output,'run python3 tools/ui_performance_abi.py'
else:
    with path.open('w',encoding='utf-8',newline='\n') as target:target.write(output)

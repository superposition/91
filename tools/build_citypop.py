def read_banks():
    result={}
    for key,name in BANKS.items():
        blob=(ROOT/'packs/citypop-sources'/name).read_bytes()
        start=blob.find(b'\xf0\x43')
        while start>=0 and blob[start+3:start+6]!=b'\x09\x20\x00':
            start=blob.find(b'\xf0\x43',start+1)
        if start<0:raise ValueError('missing DX7 bulk bank: '+name)
        msg=blob[start:start+4104]
        if len(msg)!=4104 or msg[-1]!=247 or sum(msg[6:4103])%128:
            raise ValueError('invalid SysEx length/checksum: '+name)
        result[key]=dumps(blob)[0]
    text=(ROOT/'firmware/src/dsp/fm6_dy.h').read_text(encoding='utf-8')
    body=re.sub(r'/\*.*?\*/','',text.split('static const uint8_t FM6_DY',1)[1].split('= {',1)[1],flags=re.S)
    result['dy']=[bytes(map(int,re.findall(r'\d+',row))) for row in re.findall(r'\{([^{}]+)\}',body)]
    return result


def program(key,banks,role):
    bank,index,description=VOICES[key]
    raw=banks[bank][index]
    p=list(raw)
    # Octave-normalize the written chord and bass registers. Keep all six
    # operators, their envelopes/scaling/touch, algorithm, detune and LFO intact.
    p[117]=24 if role=='keys' else 12
    return dict(name=name_of(raw),data=p),dict(id=key,name=name_of(raw),role=role,
        description=description,bank=bank,voice_index=index,algorithm=raw[110]+1,
        source_sha256=hashlib.sha256(raw).hexdigest(),
        adapted_sha256=hashlib.sha256(bytes(p)).hexdigest(),
        adaptations=[] if p[117]==raw[117] else ['transpose %d -> %d (octave only)'%(raw[117],p[117])])


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output',type=pathlib.Path,default=ROOT/'build/citypop')
    a=ap.parse_args();out=a.output;out.mkdir(parents=True,exist_ok=True)
    banks=read_banks();manifest=[];catalog={}
    header=['/* Generated by tools/build_citypop.py: custom DX7 banks, approved charts unchanged. */\n']
    for num,(stem,group) in enumerate(zip(STEMS,GROUPS)):
        original=json.loads((ROOT/'packs/standards-base'/(stem+'.json')).read_text(encoding='utf-8'))
        d=copy.deepcopy(original);d['voice_programs']=[];programs=[]
        for slot,key in enumerate(group):
            voice,record=program(key,banks,'keys' if slot<6 else 'bass')
            d['voice_programs'].append(voice);programs.append(dict(program=slot,**record));catalog[key]=record
        d['parts'].update(keys=0,bass=6,voice_flags=3,touch=50,brightness=50,keys_gate=65,attack=0,
                          keys_octave=1,bass_octave=1)
        # Every chord, form, timing pattern, drum setting and bass motif is the
        # approved arrangement. Only the instrument programs/profile change.
        for key in ('nodes','charts','forms','cadence','bass','drums'):
            assert original[key]==d[key],key
        # A larger plate leaves the keys open and bright without changing the
        # native programs or applying a second octave to their VMEM transpose.
        space={69:38,70:68,123:0,124:42,125:80}
        for setting in d['sounds']:
            if setting['parameter'] in space:setting['value']=space.pop(setting['parameter'])
        d['sounds'].extend(dict(parameter=k,value=v) for k,v in space.items())
        # Provenance is compact because the pack has a hard3840byte limit.
        d['sources']=[s for s in d['sources'] if 'DX voices:' not in s]
        d['sources'] += [SITE,
            'Custom voices: madFame Custom Patches1/2/3; Synthoxicated Pafreak1/2; DY organ/muted guitar credited in tools/fm6_dy.txt. Full program manifest accompanies this pack.',
            'Native per-operator touch and pitch LFO retained; Touch50, gate65, brightness50. Normalized VMEM; independent keys octave+1, bass+1 and spacious plate. Requires engine0.4.3.']
        b=compile_pack(d);assert compile_pack(decompile(b))==b
        (out/(stem+'.json')).write_text(json.dumps(d,indent=2)+'\n',encoding='utf-8')
        (out/(stem+'.jmp')).write_bytes(b)
        for ext in ('.json','.jmp'):(ROOT/'packs'/(stem+ext)).write_bytes((out/(stem+ext)).read_bytes())
        if num<3:
            header.append('static const uint8_t JP_SONG_%d[] = {\n'%num)
            header.extend('    '+','.join(str(x) for x in b[i:i+24])+',\n' for i in range(0,len(b),24))
            header.append('};\n')
        manifest.append(dict(name=d['name'],stem=stem,preset=num,bytes=len(b),
            crc32='%08x'%(zlib.crc32(b)&0xffffffff),sha256=hashlib.sha256(b).hexdigest(),programs=programs,
            preserved=['nodes','charts','forms','cadence','bass','drums'],
            performance_defaults=dict(keys_octave=1,bass_octave=1,reverb=38,size=68,type=0,damping=42,predelay=80)))
    (ROOT/'firmware/src/dsp/song_factory.inc').write_text(''.join(header),encoding='ascii')
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    (out/'voice-catalog.json').write_text(json.dumps(list(catalog.values()),indent=2)+'\n',encoding='utf-8')
    (ROOT/'packs/citypop-manifest.json').write_bytes((out/'manifest.json').read_bytes())
    (ROOT/'packs/voice-catalog.json').write_bytes((out/'voice-catalog.json').read_bytes())
    print(json.dumps(dict(packs=len(manifest),unique_custom_voices=len(catalog),
        pack_bytes=[m['bytes'] for m in manifest],names=[m['name'] for m in manifest]),indent=2))


if __name__=='__main__':main()

"""Keep the private input callback tags synchronized with safe Rust enums."""
from pathlib import Path
import re,sys
repo=Path(__file__).resolve().parents[1]
text=(repo/'rust/fm1-app/src/input.rs').read_text(encoding='utf-8')
lines=['/* SPDX-License-Identifier: GPL-3.0-only */','/* Generated by tools/ui_input_abi.py. */',
 '#ifndef FM1_RUST_UI_INPUT_H','#define FM1_RUST_UI_INPUT_H','#include "rust_ui.h"']
for name,prefix,base in [('Query','UIIQ',0x100),('Action','UIIA',0),('Notice','UIIN',0x200)]:
    body=re.search(r'pub enum '+name+r'\s*\{(.*?)\}',text,re.S).group(1)
    entries=re.findall(r'^\s*(\w+),\s*$',body,re.M)
    assert entries and len(entries)<256
    symbols=[prefix+'_'+re.sub(r'(?<!^)(?=[A-Z])','_',word).upper() for word in entries]
    lines.append('enum {'+symbols[0]+'='+hex(base)+','+','.join(symbols[1:])+'};')
lines+=['/* Initialized disjoint foreground UI, u32 seen and u8 held cells. All loans',
 ' * end before callbacks; no retained reference. Replaces the two old C statics. */',
 'int32_t fm1_rust_ui_input(fm1_ui_state*,uint32_t*,uint8_t*,uint32_t(*)(uint32_t,uint32_t,uint32_t));','#endif','']
output='\n'.join(lines);path=repo/'firmware/src/dsp/rust_ui_input.h'
if '--check' in sys.argv:
    assert path.read_text(encoding='utf-8')==output,'run python3 tools/ui_input_abi.py'
else:
    with path.open('w',encoding='utf-8',newline='\n') as target:target.write(output)

    for shape,k in fields(ENGAGE):
        ec += f"    memcpy(s->{k},{k},sizeof s->{k});\n" if "x" in shape else f"    s->{k}={k};\n"
    # Only three initialized fields of Config are read by engagement. Zero the
    # entire small scalar packet explicitly so all others remain initialized.
    ec += "    memset(q,0,sizeof *q);q->step_len=step_len;\n    {unsigned i;for(i=0;i<EN_NFXS;i++)q->fxs_v[i]=fxs_v[i];}\n}\n"

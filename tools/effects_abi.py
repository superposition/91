def fields(schema):
    for shape, names in schema.items():
        for name in names.split():
            yield shape, name

def decl(shape, name, rust):
    typ, *dims = shape.split("x")
    base = {"f32": "float", "u32": "uint32_t", "i32": "int32_t", "i16": "int16_t"}[typ]
    if rust:
        base = typ
        for dim in reversed(dims):
            base = f"[{base}; {dim}]"
        return f"    pub {name}: {base},\n"
    return f"    {base} {name}" + "".join(f"[{d}]" for d in dims) + ";\n"

def size(schema):
    n = 0
    for shape, _ in fields(schema):
        typ, *dims = shape.split("x")
        width = 2 if typ == "i16" else 4
        for dim in dims:
            width *= int(dim)
        n += width
    return (n + 3) // 4 * 4

def offsets(schema):
    offset=0
    for shape,name in fields(schema):
        typ,*dims=shape.split("x")
        alignment=2 if typ=="i16" else 4
        offset=(offset+alignment-1)//alignment*alignment
        yield name,offset
        width=alignment
        for dim in dims:width*=int(dim)
        offset+=width

def layout_assertions(schema,cname,rname):
    h=f'_Static_assert(_Alignof({cname})==4,"Rust FX packet alignment");\n'
    r=f'const _: [(); {size(schema)}] = [(); core::mem::size_of::<{rname}>()];\nconst _: [(); 4] = [(); core::mem::align_of::<{rname}>()];\n'
    for name,offset in offsets(schema):
        h+=f'_Static_assert(offsetof({cname},{name})=={offset},"Rust FX field {name}");\n'
        r+=f'const _: [(); {offset}] = [(); core::mem::offset_of!({rname},{name})];\n'
    return h,r

def outputs():
    h = "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/effects_abi.py. */\n#pragma once\n"

    c = "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/effects_abi.py; no delay payload copies. */\nstatic void rust_fx_control(uint32_t n)\n{\n    fm1_fx_control_state_t s;fm1_fx_control_config_t q;uint32_t action;const uint64_t mask=fx_req;\n"
    for schema, name in [(STATE, "state"), (CONFIG, "config")]:
        h += "typedef struct {\n" + "".join(decl(t, k, False) for t, k in fields(schema)) + f"}} fm1_fx_control_{name}_t;\n"

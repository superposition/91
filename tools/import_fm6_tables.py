#!/usr/bin/env python3
"""Import independently emitted C0 FM6 data with exact integer/f32 bits."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TABLES={
    'FM6_LEVELLUT':('u8',[20]),'FM6_STATICS':('i32',[77]),'FM6_VELOCITY':('u8',[64]),'FM6_EXPSCALE':('u8',[33]),'FM6_PMS':('u8',[8]),'FM6_AMS':('u32',[4]),'FM6_PEG_RATE':('u8',[100]),'FM6_PEG_STEP':('i8',[100]),'FM6_ALG':('u8',[32,6]),
    'FM6_FREQ':('i32',[1025]),'FM6_COARSE':('i32',[32]),'FM6_FINE':('i32',[128]),'FM6_DETUNE':('i64',[128]),'FM6_LFO_INC':('u32',[100]),'FM6_PORTA':('i32',[128]),'FM6_GLISS':('i32',[128]),
    'FM6_MKI_LOG_H':('u16',[1024]),'FM6_MKI_EXP_D':('u8',[512]),'FM6_OPL_LOG_H':('u16',[256]),'FM6_OPL_EXP_D':('u8',[128]),
    'FM6_INIT':('u8',[128]),'FM6_FACTORY':('u8',[8,128]),'FM6_DY':('u8',[30,128]),'FM6_ROM':('u8',[24,155]),'FM_MAP':('u8',[30]),'FM_CAP':('u8',[46]),'FM_GAIN':('f32',[46]),'FM_GAIN_DY':('f32',[30]),'FM_DX_NAME':('u8',[30,16]),'FM6_DY_NAME':('u8',[30,16]),
}
def flatten(x):
    return [v for child in x for v in flatten(child)] if isinstance(x,list) and x and isinstance(x[0],list) else x
def literal(values,shape,kind):
    if len(shape)>1:
        width=1
        for n in shape[1:]:width*=n
        return '[\n'+',\n'.join(literal(values[i*width:(i+1)*width],shape[1:],kind) for i in range(shape[0]))+'\n]'
    chunks=[]
    for at in range(0,len(values),12):
        chunks.append('    '+','.join(f'f32::from_bits({v})' if kind=='f32' else str(v) for v in values[at:at+12]))
    return '[\n'+',\n'.join(chunks)+'\n]'
def render(data):
    text='''// SPDX-License-Identifier: GPL-3.0-only
// Copyright (C) 2026 Kerem Kilic (Ellic Studio)
// Portions Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments
// DX7 measured data: MSFA (Raph Levien/Google), Dexed (Pascal Gauthier),
// Apache-2.0 / GPL-3.0-or-later, as attributed in the original C source.
// Generated by tools/import_fm6_tables.py from the independently verified C0
// export. Do not substitute mathematical approximations for these exact bits.
#![allow(dead_code)]
'''
    for name,(kind,shape) in TABLES.items():
        values=flatten(data[name]);count=1
        for n in shape:count*=n
        if len(values)!=count:raise ValueError(f'{name}: expected {count}, got {len(values)}')
        rust_type=kind
        for n in reversed(shape):rust_type=f'[{rust_type}; {n}]'
        text+=f'pub static {name}: {rust_type} = '+literal(values,shape,kind)+';\n'
    return text
def main():
    p=argparse.ArgumentParser();p.add_argument('source');p.add_argument('--check',action='store_true');args=p.parse_args()
    path=ROOT/'rust/fm1-engine/src/fm6/tables.rs';text=render(json.loads(Path(args.source).read_text()))
    if args.check:
        if path.read_text(encoding='utf-8')!=text:raise SystemExit('stale generated FM6 tables')
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
if __name__=='__main__':main()

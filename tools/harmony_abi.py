#!/usr/bin/env python3
"""Generate numeric legacy harmony packets, never pointers or audio storage."""
import argparse
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
STATE={
    'i32x12':'steps steps_nat',
    'i32':'nsteps deg hr_left chord_nt',
    'u32':'pool',
    'u8':'dom_on walk_bor deg_prev cad_n dh_n dh_i dh_ln pg_len pg_i pg_on drift_unit pg_start hist_n change_pending fifth_done drop_tonic naiwan_arc naiwan_left naiwan_rotate en_chord_alt en_walk_next_root',
    'i8':'walk_next naiwan_pending en_walk_next en_prog_pos',
    'u8x8':'dh pg_kind pg_deg pg_bars hist',
    'i32x4':'chord_pcs',
    'f32':'drift_left drift_total',
}
CONFIG={'i32':'genre root chord_kind loop_mode drift pad_oct song_oct voicing trigger','u32':'pedal playing','f32':'step_length'}
TARGETS={'f32x4':'target','i32x4':'display'}
MOOD={'f32':'arc arc_tgt brk arcm','u32':'arc_left'}
BING={'i32x4':'keys velocities'}

def fields(schema):
    for shape,names in schema.items():
        for name in names.split():yield shape,name

def packet(schema,cname,rname):
    c='typedef struct {\n';r='#[repr(C)]\n#[derive(Clone,Copy,Debug,Default)]\npub struct '+rname+' {\n'
    at=0;align=1;offsets=[]
    for shape,name in fields(schema):
        base,*dims=shape.split('x');dims=list(map(int,dims));sz=1 if base in ['u8','i8'] else 4
        at=(at+sz-1)//sz*sz;offsets.append((name,at));align=max(align,sz)
        ctype={'i32':'int32_t','u32':'uint32_t','f32':'float','u8':'uint8_t','i8':'int8_t'}[base]
        c+='    '+ctype+' '+name+''.join('['+str(n)+']' for n in dims)+';\n'
        typ=base
        for n in reversed(dims):typ='['+typ+';'+str(n)+']'
        r+='    pub '+name+':'+typ+',\n'
        n=1
        for d in dims:n*=d
        at+=sz*n
    size=(at+align-1)//align*align;c+='} '+cname+';\n';r+='}\n'
    c+=f'_Static_assert(sizeof({cname})=={size}&&_Alignof({cname})=={align},"Rust harmony {rname} layout");\n'
    r+=f'const _:[();{size}]=[();core::mem::size_of::<{rname}>()];\n'
    r+=f'const _:[();{align}]=[();core::mem::align_of::<{rname}>()];\n'
    for name,offset in offsets:
        c+=f'_Static_assert(offsetof({cname},{name})=={offset},"Rust harmony {name}");\n'
        r+=f'const _:[();{offset}]=[();core::mem::offset_of!({rname},{name})];\n'
    return c,r

def outputs():
    h='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/harmony_abi.py. */\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n'
    r='// SPDX-License-Identifier: GPL-3.0-only\n// Generated by tools/harmony_abi.py.\n'
    for schema,cname,rname in [(STATE,'fm1_harm_state_t','State'),(CONFIG,'fm1_harm_config_t','Config'),(TARGETS,'fm1_harm_targets_t','Targets'),(MOOD,'fm1_harm_mood_t','Mood'),(BING,'fm1_harm_bing_t','Bing')]:
        c,t=packet(schema,cname,rname);h+=c;r+=t
    inc='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated copies only; engine/render/drain inputs initialized; no source-state borrow retained. */\nstatic void harmony_read(fm1_harm_state_t *s,fm1_harm_config_t *c)\n{\n    memset(s,0,sizeof *s);\n'
    for shape,name in fields(STATE):
        inc+=f'    memcpy(s->{name},{name},sizeof s->{name});\n' if 'x' in shape else f'    s->{name}={name};\n'
    source={'genre':'chord_genre','root':'par[P_ROOT]','chord_kind':'par[P_CHORD]','loop_mode':'par[P_CH_LOOP]','drift':'par[P_DRIFT]','pad_oct':'par[P_PAD_OCT]','song_oct':'par[P_OCT]','voicing':'par[P_VOICING]','trigger':'par[P_DE_TRIG]','pedal':'pedal','playing':'en_playing','step_length':'step_len'}
    for _,name in fields(CONFIG):inc+=f'    c->{name}={source[name]};\n'
    inc+='}\nstatic void harmony_write(const fm1_harm_state_t *s)\n{\n'
    for shape,name in fields(STATE):
        inc+=f'    memcpy({name},s->{name},sizeof s->{name});\n' if 'x' in shape else f'    {name}=s->{name};\n'
    inc+='}\n'
    record='/* Generated field recordings; no C struct padding or inactive stack tails. */\n'
    for _,name in fields(STATE):record+=f'    record((const void *)&{name},sizeof {name});\n'
    return {'firmware/src/dsp/rust_harmony_abi.h':h,'firmware/src/dsp/rust_harmony_state.inc':inc,'rust/fm1-engine/src/harmony/abi.rs':r,'tests/reference/harmony_state.inc':record}

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,text in outputs().items():
        path=ROOT/name
        if args.check:
            if path.read_text(encoding='utf-8')!=text:raise SystemExit('stale harmony ABI:'+name)
        else:path.write_bytes(text.encode())
if __name__=='__main__':main()

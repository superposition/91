"""Private bounded knob-value ABI and inherited numeric-code assertions."""
from pathlib import Path
import re,sys
repo=Path(__file__).resolve().parents[1]
text=(repo/'rust/fm1-app/src/values.rs').read_text(encoding='utf-8')
lines=['/* SPDX-License-Identifier: GPL-3.0-only */','/* Generated by tools/ui_values_abi.py. */',
 '#ifndef FM1_RUST_UI_VALUES_H','#define FM1_RUST_UI_VALUES_H','#include "rust_ui.h"']
for name,value in re.findall(r'pub const (K_\w+):\s*i32\s*=\s*(\d+);',text):
 lines.append('_Static_assert('+name+'=='+value+',"knob code '+name+'");')
for name,prefix in [('Read','UIVR'),('Operation','UIVO')]:
 body=re.search(r'pub enum '+name+r'\s*\{(.*?)\}',text,re.S).group(1)
 entries=re.findall(r'^\s*(\w+),\s*$',body,re.M)
 assert entries and len(entries)<256
 lines.append('enum {'+','.join(prefix+'_'+re.sub(r'(?<!^)(?=[A-Z])','_',word).upper() for word in entries)+'};')
lines+=['_Static_assert(MODE_IONIAN==0 && MODE_AEOLIAN==5,"Jam mode mapping");',
 '_Static_assert(NFXP==35,"FX descriptor boundary");',
 'int32_t fm1_rust_ui_value(fm1_ui_state*,uint32_t,int32_t,int32_t,uint32_t(*)(uint32_t,uint32_t,uint32_t),int32_t(*)(uint32_t,uint8_t*,uint32_t),int32_t*);','#endif','']
output='\n'.join(lines);path=repo/'firmware/src/dsp/rust_ui_values.h'
if '--check' in sys.argv:assert path.read_text(encoding='utf-8')==output,'run python3 tools/ui_values_abi.py'
else:
 with path.open('w',encoding='utf-8',newline='\n') as target:target.write(output)

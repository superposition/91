use crate::{
    compile, decode, factory, import_midi, import_voice, inspect_midi, midi_from_log, song, Error,
    Result,
};
use serde_json::{json, Value};
use std::{
    env, fs,
    io::{Read, Write},
    path::{Path, PathBuf},
};
const USAGE:&str="usage: fm1-rs author factory|factory-song OUTPUT [--song N] | compile INPUT OUTPUT [--c-header FILE] | validate INPUT | decode INPUT OUTPUT | preview INPUT OUTPUT [--bars N --bpm N --key N --phrases N --minor] | inspect-midi INPUT | import-midi INPUT BASE OUTPUT --track N --tonic N --role bass|harmony [--bar N] [--minor] | import-voice INPUT BASE OUTPUT --role keys|bass [--voice N] | midi-log INPUT OUTPUT --bpm N";
fn root() -> PathBuf {
    env::var_os("FM1_AUTHOR_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .unwrap()
                .parent()
                .unwrap()
                .into()
        })
}
fn limits() -> Result<Option<Value>> {
    let p = root().join("build/params.json");
    if p.exists() {
        Ok(Some(serde_json::from_slice(&fs::read(p)?)?))
    } else {
        Ok(None)
    }
}
pub(crate) fn load(path: &str, limits: Option<&Value>) -> Result<Vec<u8>> {
    let p = Path::new(path);
    let b = fs::read(p)?;
    if p.extension().is_some_and(|x| x == "json") {
        compile(&serde_json::from_slice(&b)?, limits)
    } else {
        compile(decode(&b, limits)?.value(), limits)
    }
}
fn write_json(path: &str, value: &Value) -> Result<()> {
    let mut b = serde_json::to_vec_pretty(value)?;
    b.push(b'\n');
    fs::write(path, b)?;
    Ok(())
}
fn option(args: &mut Vec<String>, name: &str) -> Result<Option<String>> {
    if let Some(i) = args.iter().position(|s| s == name) {
        args.remove(i);
        if i >= args.len() {
            return Err(Error::value(format!("{name} needs a value")));
        }
        Ok(Some(args.remove(i)))
    } else {
        Ok(None)
    }
}
fn number(args: &mut Vec<String>, name: &str, default: i64) -> Result<i64> {
    option(args, name)?
        .map(|v| {
            v.parse::<i64>()
                .map_err(|_| Error::value(format!("{name}: expected an integer")))
        })
        .unwrap_or(Ok(default))
}
fn positional(args: &[String], n: usize) -> Result<()> {
    if args.len() != n || args.iter().any(|s| s.starts_with("--")) {
        Err(Error::value(USAGE))
    } else {
        Ok(())
    }
}
pub fn run(args: &[String]) -> Result<()> {
    let Some(cmd) = args.first().map(String::as_str) else {
        return Err(Error::value(USAGE));
    };
    let mut a = args[1..].to_vec();
    let limits = limits()?;
    let limits = limits.as_ref();
    match cmd {
        "preview" => {
            let bars = number(&mut a, "--bars", 16)?;
            let bpm = number(&mut a, "--bpm", 100)?;
            let key = number(&mut a, "--key", 0)?;
            let phrases = number(&mut a, "--phrases", 2)?;
            let minor = if let Some(i) = a.iter().position(|s| s == "--minor") {
                a.remove(i);
                true
            } else {
                false
            };
            positional(&a, 2)?;
            let options = crate::preview::Options::from_json(
                &json!({"bars":bars,"bpm":bpm,"key":key,"phrases":phrases,"minor":minor}),
            )?;
            println!(
                "{}",
                crate::preview::run(&root().to_string_lossy(), &a[0], &a[1], options, limits)?
            );
        }
        "factory" => {
            positional(&a, 1)?;
            write_json(&a[0], &factory())?;
        }
        "factory-song" => {
            let song_id = number(&mut a, "--song", 0)?;
            positional(&a, 1)?;
            let song_id =
                usize::try_from(song_id).map_err(|_| Error::value("song must be 0..2"))?;
            write_json(&a[0], &song(song_id)?)?;
        }
        "compile" | "decode" | "validate" => {
            let header = option(&mut a, "--c-header")?;
            positional(&a, if cmd == "validate" { 1 } else { 2 })?;
            let b = load(&a[0], limits)?;
            let d = decode(&b, limits)?;
            if cmd == "compile" {
                fs::write(&a[1], &b)?;
                if let Some(header) = header {
                    fs::write(
                        header,
                        c_header(
                            &b,
                            "JP_FACTORY",
                            "/* Generated by tools/fm1_jam.py; GPL-3.0-only */\n",
                        ),
                    )?;
                }
            } else if cmd == "decode" {
                write_json(&a[1], d.value())?;
            }
            println!(
                "{}",
                json!({"bytes":b.len(),"crc32":format!("{:08x}",fm1_formats::crc32(&b)),"name":d.value()["name"]})
            );
        }
        "inspect-midi" => {
            positional(&a, 1)?;
            println!(
                "{}",
                serde_json::to_string_pretty(&inspect_midi(&fs::read(&a[0])?)?)?
            );
        }
        "import-voice" => {
            let index = number(&mut a, "--voice", 0)?;
            let role =
                option(&mut a, "--role")?.ok_or_else(|| Error::value("--role is required"))?;
            positional(&a, 3)?;
            let d = decode(&load(&a[1], limits)?, limits)?;
            let d = import_voice(
                &fs::read(&a[0])?,
                d.value(),
                index,
                &role,
                Path::new(&a[0])
                    .file_name()
                    .unwrap_or_default()
                    .to_str()
                    .unwrap_or_default(),
                limits,
            )?;
            write_json(&a[2], &d)?;
            println!("{}", a[2]);
        }
        "import-midi" => {
            let track = number(&mut a, "--track", i64::MIN)?;
            let tonic = number(&mut a, "--tonic", i64::MIN)?;
            let bar = number(&mut a, "--bar", 1)?;
            let role =
                option(&mut a, "--role")?.ok_or_else(|| Error::value("--role is required"))?;
            let minor = if let Some(i) = a.iter().position(|s| s == "--minor") {
                a.remove(i);
                true
            } else {
                false
            };
            positional(&a, 3)?;
            if track == i64::MIN {
                return Err(Error::value("--track is required"));
            }
            if !(0..12).contains(&tonic) {
                return Err(Error::value("tonic must be 0..11"));
            }
            if !(1..=u32::MAX as i64).contains(&bar) {
                return Err(Error::value("bar is one-based"));
            }
            let d = decode(&load(&a[1], limits)?, limits)?;
            let d = import_midi(
                &fs::read(&a[0])?,
                d.value(),
                crate::midi::Selection {
                    track,
                    tonic: tonic as u8,
                    bar: bar as u32,
                    role: &role,
                    minor,
                    name: Path::new(&a[0])
                        .file_name()
                        .unwrap_or_default()
                        .to_str()
                        .unwrap_or_default(),
                },
                limits,
            )?;
            compile(&d, limits)?;
            write_json(&a[2], &d)?;
            println!("{}", a[2]);
        }
        "midi-log" => {
            let bpm = number(&mut a, "--bpm", 100)?;
            positional(&a, 2)?;
            if !(1..=60_000_000).contains(&bpm) {
                return Err(Error::value("BPM must be positive"));
            }
            fs::write(
                &a[1],
                midi_from_log(&fs::read_to_string(&a[0])?, bpm as u32)?,
            )?;
        }
        _ => return Err(Error::value(USAGE)),
    }
    Ok(())
}
pub fn c_header(b: &[u8], name: &str, prefix: &str) -> String {
    let mut s = format!("{prefix}static const uint8_t {name}[] = {{\n");
    for chunk in b.chunks(24) {
        s.push_str("    ");
        for (i, v) in chunk.iter().enumerate() {
            if i > 0 {
                s.push(',');
            }
            s.push_str(&v.to_string());
        }
        s.push_str(",\n");
    }
    s.push_str("};\n");
    s
}
pub fn api() -> Result<()> {
    let mut input = Vec::new();
    std::io::stdin()
        .take(128 * 1024 * 1024 + 1)
        .read_to_end(&mut input)?;
    if input.len() > 128 * 1024 * 1024 {
        return Err(Error::value("authoring request exceeds 128 MiB"));
    }
    let result = serde_json::from_slice(&input)
        .map_err(Error::from)
        .and_then(|v| crate::request(&v));
    let response = match result {
        Ok(v) => json!({"ok":true,"value":v}),
        Err(e) => json!({"ok":false,"kind":e.kind,"message":e.message}),
    };
    let out = serde_json::to_vec(&response)?;
    std::io::stdout().write_all(&out)?;
    Ok(())
}
/// Length-prefixed, serialized host binding; musical failures are responses and
/// never poison the next request. No document or file buffer is retained.
pub fn stream() -> Result<()> {
    let mut input = std::io::stdin().lock();
    let mut output = std::io::stdout().lock();
    loop {
        let mut size = [0u8; 4];
        match input.read(&mut size[..1])? {
            0 => return Ok(()),
            _ => input.read_exact(&mut size[1..])?,
        };
        let size = u32::from_le_bytes(size) as usize;
        if size > 128 * 1024 * 1024 {
            return Err(Error::value("authoring request exceeds 128 MiB"));
        }
        let mut bytes = vec![0; size];
        input.read_exact(&mut bytes)?;
        let result = serde_json::from_slice(&bytes)
            .map_err(Error::from)
            .and_then(|v| crate::request(&v));
        let response = match result {
            Ok(v) => json!({"ok":true,"value":v}),
            Err(e) => json!({"ok":false,"kind":e.kind,"message":e.message}),
        };
        let bytes = serde_json::to_vec(&response)?;
        output.write_all(&(bytes.len() as u32).to_le_bytes())?;
        output.write_all(&bytes)?;
        output.flush()?;
    }
}
